#!/usr/bin/env node
// SEO/KEO (11/2026), last content step of `npm run build` (before build-version/build-headers):
//   - BreadcrumbList JSON-LD on every subpage (schema only, nothing visible), between <!-- breadcrumb-jsonld --> markers,
//     the page name taken from its <h1>
//   - public/sitemap.xml from every page that is not noindex; <loc> is the page's canonical URL, <lastmod> the date of
//     the last git commit of the page file (today when the file has uncommitted changes or git is unavailable)
//   - gates: every JSON-LD block on every page parses, every indexable page has a canonical, exactly one IndexNow key
//     file public/<32 hex>.txt that contains only its key, llms.txt states the prices from offer.json and both founders.
// The IndexNow ping itself runs in .github/workflows/indexnow.yml after a push to main.
import {execFileSync} from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const PUB = path.join(ROOT, 'public');
const BASE = 'https://bartolucci-digital.de/';
const fail = (msg) => { console.error('build-seo: ' + msg); process.exit(1); };
const today = new Date().toISOString().slice(0, 10);
const git = (...args) => { try { return execFileSync('git', args, {cwd: ROOT, encoding: 'utf8'}).trim(); } catch { return ''; } };
const lastmod = (rel) => (git('status', '--porcelain', '--', rel) ? '' : git('log', '-1', '--format=%cs', '--', rel)) || today;

const pages = fs.readdirSync(PUB).filter((f) => f.endsWith('.html')).sort();
const urls = [];
for (const file of pages) {
  const full = path.join(PUB, file);
  let html = fs.readFileSync(full, 'utf8');
  const noindex = /<meta name="robots" content="[^"]*noindex/.test(html);
  const canonical = (/<link rel="canonical" href="([^"]+)">/.exec(html) || [])[1];
  if (!noindex && !canonical) fail(`${file}: indexable page without canonical`);

  if (canonical && canonical !== BASE) {
    const name = ((/<h1[^>]*>([^<]+)</.exec(html) || [])[1] || '').trim();
    if (!name) fail(`${file}: no <h1> for the breadcrumb name`);
    const ld = {'@context': 'https://schema.org', '@type': 'BreadcrumbList', itemListElement: [
      {'@type': 'ListItem', position: 1, name: 'Startseite', item: BASE},
      {'@type': 'ListItem', position: 2, name, item: canonical},
    ]};
    const block = `<!-- breadcrumb-jsonld:start (generated by scripts/build-seo.mjs) -->\n<script type="application/ld+json">${JSON.stringify(ld)}</script>\n<!-- breadcrumb-jsonld:end -->`;
    const re = /<!-- breadcrumb-jsonld:start[\s\S]*?<!-- breadcrumb-jsonld:end -->/;
    const out = re.test(html) ? html.replace(re, () => block) : html.replace('</head>', () => block + '\n</head>');
    if (out !== html) fs.writeFileSync(full, out);
    html = out;
  }

  for (const [, json] of html.matchAll(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/g)) {
    try { JSON.parse(json); } catch (e) { fail(`${file}: JSON-LD does not parse: ${e.message}`); }
  }
  if (!noindex) urls.push({loc: canonical, lastmod: lastmod(`public/${file}`)});
}

urls.sort((a, b) => (a.loc === BASE ? -1 : b.loc === BASE ? 1 : a.loc.localeCompare(b.loc)));
const xml = '<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
  + urls.map((u) => `  <url>\n    <loc>${u.loc}</loc>\n    <lastmod>${u.lastmod}</lastmod>\n  </url>\n`).join('') + '</urlset>\n';
fs.writeFileSync(path.join(PUB, 'sitemap.xml'), xml);

const keys = fs.readdirSync(PUB).filter((f) => /^[0-9a-f]{32}\.txt$/.test(f));
if (keys.length !== 1) fail(`expected exactly one IndexNow key file, found ${keys.length}`);
if (fs.readFileSync(path.join(PUB, keys[0]), 'utf8').trim() !== keys[0].slice(0, 32)) fail(`${keys[0]} must contain only its key`);

const llms = fs.readFileSync(path.join(PUB, 'llms.txt'), 'utf8');
const offer = JSON.parse(fs.readFileSync(path.join(PUB, 'data', 'offer.json'), 'utf8'));
const company = JSON.parse(fs.readFileSync(path.join(PUB, 'data', 'company.json'), 'utf8'));
const eur = (n) => n.toLocaleString('de-DE') + ' €';
for (const s of [eur(offer.launchPrice), eur(offer.regularPrice), eur(offer.carePrice), eur(offer.roundPrice), company.email, ...company.founders.map((f) => f.name)]) {
  if (!llms.includes(s)) fail(`llms.txt does not contain "${s}" (keep it in line with offer.json / company.json)`);
}
console.log(`build-seo: sitemap ${urls.length} URL(s) [${urls.map((u) => u.loc + ' ' + u.lastmod).join(', ')}], breadcrumbs, JSON-LD parse ok, key ${keys[0]}`);
