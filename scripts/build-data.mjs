#!/usr/bin/env node
// Bundles public/data/chapters.json + public/data/offer.json + public/frames/manifest.json into
// public/data/site-data.js (window.BD). The page cannot fetch() JSON because the CSP sets
// connect-src 'none' (zero network calls beyond the assets themselves), so the data ships as a
// plain script. Run after editing offer.json or chapters.json: `npm run build`.
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const PUB = path.join(ROOT, 'public');
const read = (p) => JSON.parse(fs.readFileSync(path.join(PUB, p), 'utf8'));

const chapters = read('data/chapters.json');
const offer = read('data/offer.json');
const manifestPath = path.join(PUB, 'frames', 'manifest.json');
const manifest = fs.existsSync(manifestPath) ? JSON.parse(fs.readFileSync(manifestPath, 'utf8')) : null;

for (const k of ['launchPrice', 'regularPrice', 'slotsTotal', 'slotsLeft', 'carePrice']) {
  if (typeof offer[k] !== 'number') throw new Error(`offer.json: "${k}" must be a number`);
}
if (offer.slotsLeft < 0 || offer.slotsLeft > offer.slotsTotal) throw new Error('offer.json: slotsLeft out of range');

const data = {
  video: chapters.video,
  chapters: chapters.chapters.map(({id, index, label, start, end, scrubStart}) => ({id, index, label, start, end, scrubStart: scrubStart ?? start})),
  frames: manifest ? {fps: manifest.fps, width: manifest.width, chapters: Object.fromEntries(Object.entries(manifest.chapters).map(([id, c]) => [id, {count: c.count, firstTime: c.firstTime, lastTime: c.lastTime}]))} : null,
  offer,
  built: new Date().toISOString().slice(0, 10),
};
const out = `// generated by scripts/build-data.mjs – do not edit, edit public/data/*.json instead\nwindow.BD = ${JSON.stringify(data)};\n`;
fs.writeFileSync(path.join(PUB, 'data', 'site-data.js'), out);
console.log(`site-data.js written (${out.length} bytes, frames: ${manifest ? 'yes' : 'no manifest yet'})`);
