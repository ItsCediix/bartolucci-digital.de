#!/usr/bin/env node
// Bundles public/data/chapters.json + public/data/offer.json into public/data/site-data.js (window.BD).
// The page cannot fetch() JSON because the CSP sets connect-src 'none' (zero network calls beyond the
// assets themselves), so the data ships as a plain script. Run after editing offer.json or
// chapters.json: `npm run build`.
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const PUB = path.join(ROOT, 'public');
const read = (p) => JSON.parse(fs.readFileSync(path.join(PUB, p), 'utf8'));

const chapters = read('data/chapters.json');
const offer = read('data/offer.json');

for (const k of ['launchPrice', 'regularPrice', 'slotsTotal', 'slotsLeft', 'carePrice']) {
  if (typeof offer[k] !== 'number') throw new Error(`offer.json: "${k}" must be a number`);
}
if (offer.slotsLeft < 0 || offer.slotsLeft > offer.slotsTotal) throw new Error('offer.json: slotsLeft out of range');
for (const c of chapters.chapters) {
  if (!Array.isArray(c.beats) || c.beats.length < 1) throw new Error(`chapters.json: "${c.id}" needs a beats array`);
}

const data = {
  chapters: chapters.chapters.map(({id, index, label, vh, beats}) => ({id, index, label, vh, beats: beats.map((b) => b.at)})),
  offer,
  built: new Date().toISOString().slice(0, 10),
};
const out = `// generated by scripts/build-data.mjs – do not edit, edit public/data/*.json instead\nwindow.BD = ${JSON.stringify(data)};\n`;
fs.writeFileSync(path.join(PUB, 'data', 'site-data.js'), out);
console.log(`site-data.js written (${out.length} bytes)`);
