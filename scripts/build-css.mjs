#!/usr/bin/env node
// v18 (audit M16, safe part): one stylesheet for the start page. base.css, scenes.css, desktop.css and mobile.css
// stay the editable sources (the legal pages and 404.html keep loading base.css alone); this script concatenates
// them in the cascade order index.html used to link them and writes public/assets/site.css, so the start page
// makes one render-blocking CSS request instead of four. Every url() in the sources is absolute, so nothing moves.
// Not done on purpose: inlining "critical CSS" with the rest loaded asynchronously. That needs an onload handler
// on the <link> (forbidden by the CSP, no 'unsafe-inline' or 'unsafe-hashes' for scripts) or a JavaScript loader,
// which would put the first paint back behind JavaScript, the very thing M1 removes. Part of `npm run build`.
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const ASSETS = path.join(ROOT, 'public', 'assets');
const SOURCES = ['base.css', 'scenes.css', 'desktop.css', 'mobile.css'];
const parts = SOURCES.map((f) => {
  const css = fs.readFileSync(path.join(ASSETS, f), 'utf8').replace(/\r\n/g, '\n').replace(/\s+$/, '');
  return `/* ======== ${f} (source: public/assets/${f}, bundled by scripts/build-css.mjs) ======== */\n${css}\n`;
});
const out = `/* generated by scripts/build-css.mjs, do not edit: edit public/assets/{${SOURCES.join(',')}} and run npm run build */\n` + parts.join('\n');
const file = path.join(ASSETS, 'site.css');
const before = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
if (before !== out) fs.writeFileSync(file, out);
console.log(`build-css: site.css ${out.length} bytes from ${SOURCES.length} files${before === out ? ' (unchanged)' : ''}`);
